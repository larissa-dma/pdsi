ALTER TABLE usuario ADD COLUMN senha_hash VARCHAR(100),
 ADD COLUMN perfil VARCHAR(20) NOT NULL DEFAULT 'HOSPEDAGEM' CHECK (perfil IN ('SECRETARIA','HOSPEDAGEM')),
 ADD COLUMN estabelecimento_id BIGINT REFERENCES registro_inventario(id);
CREATE TABLE formulario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo VARCHAR(200) NOT NULL, referencia VARCHAR(50) NOT NULL,
 prazo DATE NOT NULL, perguntas JSONB NOT NULL,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE formulario_resposta (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 formulario_id BIGINT NOT NULL REFERENCES formulario(id),
 estabelecimento_id BIGINT NOT NULL REFERENCES registro_inventario(id),
 respostas JSONB NOT NULL DEFAULT '{}',
 status VARCHAR(15) NOT NULL DEFAULT 'rascunho' CHECK (status IN ('rascunho','enviado')),
 atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(), enviado_em TIMESTAMPTZ,
 UNIQUE(formulario_id, estabelecimento_id)
);
