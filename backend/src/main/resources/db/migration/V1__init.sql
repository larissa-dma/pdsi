-- Observatório de Turismo de Olímpia (OTO)
-- Versão inicial do esquema PostgreSQL alinhada ao DER do Figma.
-- ATENÇÃO: modelo PROVISÓRIO. Confirmar dicionários de dados, grão e campos com o OTO.
-- Executar dentro do banco "oto" (o Docker Compose cria esse banco).

BEGIN;

-- 1) Cadastro mestre do inventário
CREATE TABLE IF NOT EXISTS categoria_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS registro_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL REFERENCES categoria_inventario(id) ON DELETE RESTRICT,
    nome VARCHAR(200) NOT NULL,
    descricao TEXT,
    endereco VARCHAR(255),
    bairro VARCHAR(120),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    CONSTRAINT ck_inventario_lat CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_inventario_lon CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_inventario_coords_pares CHECK ((latitude IS NULL) = (longitude IS NULL))
);

-- 2) Origem, catálogo dos conjuntos e histórico das cargas
CREATE TABLE IF NOT EXISTS fonte_dados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    descricao TEXT,
    situacao_carga VARCHAR(30) NOT NULL DEFAULT 'pendente'
);

CREATE TABLE IF NOT EXISTS conjunto_pesquisa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    descricao TEXT,
    codigo VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    identificador VARCHAR(200) NOT NULL UNIQUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS importacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte_id BIGINT NOT NULL REFERENCES fonte_dados(id) ON DELETE RESTRICT,
    -- NULL permitido apenas para cargas sem conjunto de pesquisa (p.ex. inventário).
    -- Esta regra por domínio ainda precisa de validação.
    conjunto_id BIGINT REFERENCES conjunto_pesquisa(id) ON DELETE RESTRICT,
    usuario_responsavel_id BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
    referencia VARCHAR(50) NOT NULL,
    nome_arquivo VARCHAR(255) NOT NULL,
    hash_arquivo VARCHAR(128),
    status VARCHAR(30) NOT NULL DEFAULT 'recebida',
    linhas_total INTEGER NOT NULL DEFAULT 0 CHECK (linhas_total >= 0),
    linhas_validas INTEGER NOT NULL DEFAULT 0 CHECK (linhas_validas >= 0),
    linhas_pendentes INTEGER NOT NULL DEFAULT 0 CHECK (linhas_pendentes >= 0),
    data_importacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_contagem_importacao CHECK (linhas_validas + linhas_pendentes <= linhas_total)
);

CREATE TABLE IF NOT EXISTS erro_importacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES importacao(id) ON DELETE RESTRICT,
    linha INTEGER NOT NULL CHECK (linha > 0),
    campo VARCHAR(100),
    tipo VARCHAR(50) NOT NULL,
    descricao TEXT NOT NULL
);

-- 3) Registros analíticos do MVP
-- O vínculo com estabelecimento é opcional: séries agregadas podem não identificar um.
CREATE TABLE IF NOT EXISTS ocupacao_fluxo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES importacao(id) ON DELETE RESTRICT,
    estabelecimento_id BIGINT REFERENCES registro_inventario(id) ON DELETE RESTRICT,
    mes_referencia DATE NOT NULL,
    ocupacao_percentual NUMERIC(5,2)
        CHECK (ocupacao_percentual >= 0 AND ocupacao_percentual <= 100),
    fluxo_pessoas INTEGER CHECK (fluxo_pessoas >= 0),
    tipo_dado VARCHAR(20) NOT NULL
        CHECK (tipo_dado IN ('consolidado', 'expectativa')),
    linha_origem INTEGER CHECK (linha_origem > 0),
    dados_originais JSONB,
    CONSTRAINT ck_ocupacao_mes CHECK (EXTRACT(DAY FROM mes_referencia) = 1)
);

CREATE TABLE IF NOT EXISTS diaria_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES importacao(id) ON DELETE RESTRICT,
    estabelecimento_id BIGINT REFERENCES registro_inventario(id) ON DELETE RESTRICT,
    mes_referencia DATE NOT NULL,
    valor NUMERIC(12,2) CHECK (valor >= 0),
    linha_origem INTEGER CHECK (linha_origem > 0),
    dados_originais JSONB,
    CONSTRAINT ck_diaria_mes CHECK (EXTRACT(DAY FROM mes_referencia) = 1)
);

CREATE TABLE IF NOT EXISTS demanda_turistica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES importacao(id) ON DELETE RESTRICT,
    referencia VARCHAR(50) NOT NULL,
    origem_uf CHAR(2),
    linha_origem INTEGER CHECK (linha_origem > 0),
    dados_originais JSONB,
    CONSTRAINT ck_demanda_uf CHECK (origem_uf IS NULL OR origem_uf ~ '^[A-Z]{2}$')
);

CREATE TABLE IF NOT EXISTS controle_pesquisa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES importacao(id) ON DELETE RESTRICT,
    conjunto_id BIGINT NOT NULL REFERENCES conjunto_pesquisa(id) ON DELETE RESTRICT,
    referencia VARCHAR(50) NOT NULL,
    linha_origem INTEGER CHECK (linha_origem > 0),
    dados_originais JSONB
);

-- 4) Entidades complementares para indicadores e ODS (fase posterior)
CREATE TABLE IF NOT EXISTS indicador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    unidade VARCHAR(60) NOT NULL,
    metodologia TEXT
);

CREATE TABLE IF NOT EXISTS observacao_indicador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicador_id BIGINT NOT NULL REFERENCES indicador(id) ON DELETE RESTRICT,
    fonte_id BIGINT NOT NULL REFERENCES fonte_dados(id) ON DELETE RESTRICT,
    lote_id BIGINT REFERENCES importacao(id) ON DELETE RESTRICT,
    referencia VARCHAR(50) NOT NULL,
    valor NUMERIC(18,4)
);

CREATE TABLE IF NOT EXISTS ods (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero INTEGER NOT NULL UNIQUE CHECK (numero BETWEEN 1 AND 17),
    nome VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS indicador_ods (
    indicador_id BIGINT NOT NULL REFERENCES indicador(id) ON DELETE CASCADE,
    ods_id INTEGER NOT NULL REFERENCES ods(id) ON DELETE CASCADE,
    justificativa TEXT,
    PRIMARY KEY (indicador_id, ods_id)
);

-- 5) Relatórios e exportações (fase posterior)
CREATE TABLE IF NOT EXISTS relatorio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    recorte TEXT,
    versao_metodologica VARCHAR(80)
);

CREATE TABLE IF NOT EXISTS exportacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relatorio_id BIGINT NOT NULL REFERENCES relatorio(id) ON DELETE RESTRICT,
    formato VARCHAR(10) NOT NULL CHECK (formato IN ('pdf', 'xlsx', 'csv')),
    data_exportacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status VARCHAR(30) NOT NULL,
    referencia_arquivo VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS relatorio_lote (
    relatorio_id BIGINT NOT NULL REFERENCES relatorio(id) ON DELETE CASCADE,
    lote_id BIGINT NOT NULL REFERENCES importacao(id) ON DELETE RESTRICT,
    PRIMARY KEY (relatorio_id, lote_id)
);

-- 6) Índices para relacionamentos e consultas frequentes
CREATE INDEX IF NOT EXISTS idx_inventario_categoria_bairro ON registro_inventario(categoria_id, bairro);
CREATE INDEX IF NOT EXISTS idx_importacao_fonte ON importacao(fonte_id);
CREATE INDEX IF NOT EXISTS idx_importacao_conjunto ON importacao(conjunto_id);
CREATE INDEX IF NOT EXISTS idx_importacao_responsavel ON importacao(usuario_responsavel_id);
CREATE INDEX IF NOT EXISTS idx_importacao_data ON importacao(data_importacao DESC);
CREATE INDEX IF NOT EXISTS idx_erro_lote_linha ON erro_importacao(lote_id, linha);
CREATE INDEX IF NOT EXISTS idx_ocupacao_mes_tipo ON ocupacao_fluxo(mes_referencia, tipo_dado);
CREATE INDEX IF NOT EXISTS idx_ocupacao_lote ON ocupacao_fluxo(lote_id);
CREATE INDEX IF NOT EXISTS idx_ocupacao_estabelecimento ON ocupacao_fluxo(estabelecimento_id);
CREATE INDEX IF NOT EXISTS idx_diaria_mes ON diaria_media(mes_referencia);
CREATE INDEX IF NOT EXISTS idx_diaria_lote ON diaria_media(lote_id);
CREATE INDEX IF NOT EXISTS idx_diaria_estabelecimento ON diaria_media(estabelecimento_id);
CREATE INDEX IF NOT EXISTS idx_demanda_lote ON demanda_turistica(lote_id);
CREATE INDEX IF NOT EXISTS idx_controle_lote ON controle_pesquisa(lote_id);
CREATE INDEX IF NOT EXISTS idx_controle_conjunto ON controle_pesquisa(conjunto_id);
CREATE INDEX IF NOT EXISTS idx_observacao_indicador_referencia ON observacao_indicador(indicador_id, referencia);
CREATE INDEX IF NOT EXISTS idx_observacao_fonte ON observacao_indicador(fonte_id);
CREATE INDEX IF NOT EXISTS idx_observacao_lote ON observacao_indicador(lote_id);
CREATE INDEX IF NOT EXISTS idx_exportacao_relatorio ON exportacao(relatorio_id);
CREATE INDEX IF NOT EXISTS idx_relatorio_lote_lote ON relatorio_lote(lote_id);

COMMIT;
