ALTER TABLE usuario ADD COLUMN versao_senha INTEGER NOT NULL DEFAULT 0;
CREATE TABLE importacao_previa (
 id UUID PRIMARY KEY, usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 nome_arquivo VARCHAR(255) NOT NULL, hash_arquivo VARCHAR(64) NOT NULL,
 colunas JSONB NOT NULL, linhas JSONB NOT NULL,
 tipo VARCHAR(30), referencia VARCHAR(50), mapeamento JSONB,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
 confirmado_id BIGINT REFERENCES importacao(id)
);
ALTER TABLE importacao ADD COLUMN tipo_importacao VARCHAR(30);
CREATE UNIQUE INDEX importacao_hash_tipo_unico ON importacao(hash_arquivo,tipo_importacao) WHERE hash_arquivo IS NOT NULL AND tipo_importacao IS NOT NULL;
CREATE TABLE auditoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 identificador VARCHAR(200), metodo VARCHAR(10) NOT NULL, caminho TEXT NOT NULL,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX auditoria_data_idx ON auditoria(criado_em DESC);
CREATE INDEX resposta_estabelecimento_idx ON formulario_resposta(estabelecimento_id);
