CREATE TABLE observacao_externa (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lote_id BIGINT NOT NULL REFERENCES importacao(id),
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('issqn','caged','veiculos','fretamento')),
 mes_referencia DATE NOT NULL CHECK(EXTRACT(DAY FROM mes_referencia)=1),
 medida VARCHAR(100) NOT NULL, unidade VARCHAR(60) NOT NULL,
 recorte TEXT, valor NUMERIC(18,4) NOT NULL,
 linha_origem INTEGER NOT NULL
);
CREATE INDEX observacao_externa_tipo_mes ON observacao_externa(tipo,mes_referencia);
CREATE TABLE importacao_linha (
 lote_id BIGINT NOT NULL REFERENCES importacao(id),linha INTEGER NOT NULL,
 dados_originais JSONB NOT NULL,valida BOOLEAN NOT NULL,
 PRIMARY KEY(lote_id,linha)
);
