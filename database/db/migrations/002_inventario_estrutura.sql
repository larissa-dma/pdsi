-- Exemplo prático: UH, leitos e UH acessível, SEM misturar contagem com pergunta booleana.
CREATE VIEW vw_hospedagem_capacidade AS
SELECT v.registro_id,
       MAX(r.valor_inteiro) FILTER (WHERE c.coluna_excel='AA') AS unidades_habitacionais,
       MAX(r.valor_inteiro) FILTER (WHERE c.coluna_excel='AB') AS leitos,
       MAX(r.valor_inteiro) FILTER (WHERE c.coluna_excel='AC') AS unidades_habitacionais_pcd
FROM inventario_vinculo_segmento v
JOIN inventario_segmento s ON s.id=v.segmento_id AND s.codigo='hospedagem'
LEFT JOIN inventario_resposta r ON r.vinculo_id=v.id
LEFT JOIN inventario_campo c ON c.id=r.campo_id
GROUP BY v.registro_id;
COMMIT;
