    ADD CONSTRAINT registro_conferencia_ck CHECK (situacao_conferencia IN ('pendente','parcial','conferido','rejeitado'));

CREATE TABLE inventario_segmento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nome VARCHAR(160) NOT NULL UNIQUE,
    aba_original VARCHAR(120) NOT NULL UNIQUE,
    linha_cabecalho SMALLINT NOT NULL CHECK (linha_cabecalho BETWEEN 1 AND 20)
);

CREATE TABLE inventario_vinculo_segmento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_id BIGINT NOT NULL REFERENCES registro_inventario(id) ON DELETE RESTRICT,
    segmento_id BIGINT NOT NULL REFERENCES inventario_segmento(id) ON DELETE RESTRICT,
    lote_id BIGINT REFERENCES importacao(id) ON DELETE RESTRICT,
    id_excel_origem TEXT,
    linha_excel_origem INTEGER CHECK (linha_excel_origem > 0),
    situacao_conferencia VARCHAR(25) NOT NULL DEFAULT 'pendente'
        CHECK (situacao_conferencia IN ('pendente','parcial','conferido','rejeitado')),
    UNIQUE (registro_id, segmento_id)
);

-- As 9 abas visíveis definem segmentos; a aba oculta não é um 10º segmento.
-- Colunas sem definição permanecem no catálogo para auditoria, mas não viram respostas obrigatórias.
CREATE TABLE inventario_campo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave_tecnica VARCHAR(100) NOT NULL UNIQUE,
    segmento_id BIGINT REFERENCES inventario_segmento(id) ON DELETE RESTRICT,
    aba_original VARCHAR(120) NOT NULL,
    coluna_excel VARCHAR(4) NOT NULL,
    grupo_original TEXT NOT NULL,
    campo_original TEXT NOT NULL,
    tipo_observado TEXT NOT NULL,
    tipo_recomendado VARCHAR(60) NOT NULL,
    tipo_logico VARCHAR(40) NOT NULL CHECK (tipo_logico IN
      ('texto','selecao','inteiro','decimal','percentual','booleano',
       'booleano_detalhe','texto_indicacao','data','data_ou_ano',
       'lista_texto','coordenadas','sem_definicao')),
    tipo_sql_sugerido TEXT NOT NULL,
    regra_tratamento TEXT NOT NULL,
    auxiliar BOOLEAN NOT NULL DEFAULT FALSE,
    obrigatorio BOOLEAN, -- NULL: não decidido pelo OTO
    UNIQUE (aba_original,coluna_excel),
    CHECK ((segmento_id IS NULL) = auxiliar)
);

-- Uma linha de resposta para cada posição da planilha e vínculo com o segmento.
-- Tipos físicos não são inferidos do formato Excel; são escolhidos pelo sentido do campo.
CREATE TABLE inventario_resposta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculo_id BIGINT NOT NULL REFERENCES inventario_vinculo_segmento(id) ON DELETE CASCADE,
    campo_id BIGINT NOT NULL REFERENCES inventario_campo(id) ON DELETE RESTRICT,
    valor_texto TEXT,
    valor_inteiro INTEGER CHECK (valor_inteiro >= 0),
    valor_decimal NUMERIC(14,4),
    valor_booleano BOOLEAN,
    valor_data DATE,
    valor_ano SMALLINT CHECK (valor_ano BETWEEN 1000 AND 9999),
    valor_lista TEXT[],
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    texto_original TEXT,
    observacao TEXT,
    situacao_validacao VARCHAR(22) NOT NULL DEFAULT 'pendente'
         CHECK (situacao_validacao IN ('pendente','valido','revisar','nao_aplicavel')),
    ficticio BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (vinculo_id,campo_id),
    CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CHECK (latitude BETWEEN -90 AND 90),
    CHECK (longitude BETWEEN -180 AND 180)
);

-- Impede campo de um segmento ser usado em outro e converte categoria em regra de tipagem.
CREATE OR REPLACE FUNCTION validar_resposta_inventario()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE t VARCHAR(40); seg BIGINT; seg_vinculo BIGINT;
BEGIN
  SELECT tipo_logico, segmento_id INTO t, seg FROM inventario_campo WHERE id=NEW.campo_id;
  SELECT segmento_id INTO seg_vinculo FROM inventario_vinculo_segmento WHERE id=NEW.vinculo_id;
  IF seg IS NULL OR seg <> seg_vinculo THEN
    RAISE EXCEPTION 'Campo não pertence ao segmento do cadastro: campo %, vínculo %', NEW.campo_id, NEW.vinculo_id;
  END IF;
  IF NEW.valor_decimal IS NOT NULL AND t='percentual' AND
     (NEW.valor_decimal < 0 OR NEW.valor_decimal > 100) THEN
    RAISE EXCEPTION 'Percentual fora da escala 0..100';
  END IF;
  IF NEW.valor_ano IS NOT NULL AND t <> 'data_ou_ano' THEN
    RAISE EXCEPTION 'Ano parcial em campo de outro tipo';
  END IF;
  IF t IN ('texto','selecao') AND (NEW.valor_texto IS NULL OR
    num_nonnulls(NEW.valor_inteiro,NEW.valor_decimal,NEW.valor_booleano,NEW.valor_data,
      NEW.valor_ano,NEW.valor_lista,NEW.latitude) > 0) THEN
    RAISE EXCEPTION 'Tipo inválido: texto/seleção';
  ELSIF t = 'inteiro' AND (NEW.valor_inteiro IS NULL OR
    num_nonnulls(NEW.valor_texto,NEW.valor_decimal,NEW.valor_booleano,NEW.valor_data,
      NEW.valor_ano,NEW.valor_lista,NEW.latitude)>0) THEN
    RAISE EXCEPTION 'Tipo inválido: inteiro';
  ELSIF t IN ('decimal','percentual') AND (NEW.valor_decimal IS NULL OR
    num_nonnulls(NEW.valor_texto,NEW.valor_inteiro,NEW.valor_booleano,NEW.valor_data,
      NEW.valor_ano,NEW.valor_lista,NEW.latitude)>0) THEN
    RAISE EXCEPTION 'Tipo inválido: decimal';
  ELSIF t='booleano' AND (NEW.valor_booleano IS NULL OR
    num_nonnulls(NEW.valor_texto,NEW.valor_inteiro,NEW.valor_decimal,NEW.valor_data,
      NEW.valor_ano,NEW.valor_lista,NEW.latitude)>0) THEN
    RAISE EXCEPTION 'Tipo inválido: booleano';
  ELSIF t='data' AND (NEW.valor_data IS NULL OR
    num_nonnulls(NEW.valor_texto,NEW.valor_inteiro,NEW.valor_decimal,NEW.valor_booleano,
      NEW.valor_ano,NEW.valor_lista,NEW.latitude)>0) THEN
    RAISE EXCEPTION 'Tipo inválido: data';
  ELSIF t='data_ou_ano' AND (num_nonnulls(NEW.valor_data,NEW.valor_ano)<>1 OR
    num_nonnulls(NEW.valor_texto,NEW.valor_inteiro,NEW.valor_decimal,NEW.valor_booleano,
      NEW.valor_lista,NEW.latitude)>0) THEN
    RAISE EXCEPTION 'Tipo inválido: data ou ano';
  ELSIF t='lista_texto' AND (NEW.valor_lista IS NULL OR
    num_nonnulls(NEW.valor_texto,NEW.valor_inteiro,NEW.valor_decimal,NEW.valor_booleano,
      NEW.valor_data,NEW.valor_ano,NEW.latitude)>0) THEN
    RAISE EXCEPTION 'Tipo inválido: lista';
  ELSIF t='coordenadas' AND (NEW.latitude IS NULL OR NEW.longitude IS NULL OR
    num_nonnulls(NEW.valor_texto,NEW.valor_inteiro,NEW.valor_decimal,NEW.valor_booleano,
      NEW.valor_data,NEW.valor_ano,NEW.valor_lista)>0) THEN
    RAISE EXCEPTION 'Tipo inválido: coordenadas';
  ELSIF t IN ('booleano_detalhe','texto_indicacao') AND
    (num_nonnulls(NEW.valor_texto,NEW.valor_booleano)<1 OR
     num_nonnulls(NEW.valor_inteiro,NEW.valor_decimal,NEW.valor_data,NEW.valor_ano,
       NEW.valor_lista,NEW.latitude)>0) THEN
    RAISE EXCEPTION 'Tipo inválido: booleano com detalhe';
  ELSIF t='sem_definicao' AND
    num_nonnulls(NEW.valor_texto,NEW.valor_inteiro,NEW.valor_decimal,NEW.valor_booleano,
     NEW.valor_data,NEW.valor_ano,NEW.valor_lista,NEW.latitude)>0 THEN
    RAISE EXCEPTION 'Campo sem definição não aceita valor tipado';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_tipo_resposta_inventario
BEFORE INSERT OR UPDATE ON inventario_resposta
FOR EACH ROW EXECUTE FUNCTION validar_resposta_inventario();

-- Armazenamentos relacionais adicionais para campos multivalorados.
CREATE TABLE inventario_canal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_id BIGINT NOT NULL REFERENCES registro_inventario(id) ON DELETE CASCADE,
    tipo VARCHAR(22) NOT NULL CHECK (tipo IN ('telefone','email','site','rede_social','outro')),
