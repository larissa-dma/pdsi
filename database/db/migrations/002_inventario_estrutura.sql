CREATE TABLE inventario_atividade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_id BIGINT NOT NULL REFERENCES registro_inventario(id) ON DELETE CASCADE,
